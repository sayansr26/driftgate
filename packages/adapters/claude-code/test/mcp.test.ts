import { describe, expect, it } from 'vitest';
import type { Canonical, McpServer } from '@rulegate/adapter-kit';
import { claudeCode, CLAUDE_MD, MCP_FILE } from '../src/index.js';
import {
  contextFor,
  expectFixtureMatch,
  expectIdempotent,
  renderFixture,
} from '@rulegate/adapter-kit/testing';

const FIXTURE = 'claude-code-mcp';

async function render(mutate: (c: Canonical) => Canonical = (c) => c): Promise<string | undefined> {
  const ctx = await contextFor(`${FIXTURE}/input`, claudeCode);
  const artifacts = await claudeCode.write({ ...ctx, canonical: mutate(ctx.canonical) });
  return artifacts.find((a) => a.path === MCP_FILE)?.contents;
}

describe('claude-code MCP output (T046)', () => {
  it('matches the hand-written golden byte for byte', async () => {
    await expectFixtureMatch(FIXTURE, claudeCode);
  });

  it('is idempotent across repeated renders', async () => {
    await expectIdempotent(FIXTURE, claudeCode);
  });

  it('generates MCP for a repository with servers and no rules', async () => {
    // The regression this fixture exists for: `write()` used to return early when no rule
    // targeted the tool, which would have made canonical MCP unreachable.
    const actual = await renderFixture(FIXTURE, claudeCode);
    expect([...actual.keys()]).toEqual([MCP_FILE]);
  });

  it('renders the artifact as kind `mcp` with no provenance', async () => {
    const ctx = await contextFor(`${FIXTURE}/input`, claudeCode);
    const artifact = (await claudeCode.write(ctx)).find((a) => a.path === MCP_FILE);

    expect(artifact?.kind).toBe('mcp');
    // No canonical rule contributed, and claiming one would mislead `doctor` and T051.
    expect(artifact?.provenance).toBeUndefined();
  });

  it('skips disabled, global-scope, and other-tool servers', async () => {
    const contents = (await render()) ?? '';
    expect(contents).not.toContain('disabled-server');
    expect(contents).not.toContain('user-global');
    expect(contents).not.toContain('cursor-only');
  });

  it('spells an env reference the way Claude Code expands it', async () => {
    const contents = (await render()) ?? '';
    // `${NAME}`, not Cursor's `${env:NAME}` and never Rulegate's own `env:NAME` — the
    // last of which would hand the server the literal string as its credential.
    expect(contents).toContain('"GITHUB_TOKEN": "${GITHUB_TOKEN}"');
    expect(contents).not.toContain('${env:');
    expect(contents).not.toContain('"env:');
  });

  it('distinguishes sse from http, which are both a bare url', async () => {
    const contents = (await render()) ?? '';
    expect(contents).toContain('"type": "sse"');
    expect(contents).toContain('"type": "http"');
  });

  it('re-emits keys Rulegate does not interpret', async () => {
    // RFC-0001 §11.1. It is also the only path by which a literal secret can reach
    // generated output, which is what T044's scan over rendered bytes exists for.
    expect((await render()) ?? '').toContain('"timeout": 600000');
  });

  it('is valid JSON whose marker key sorts first', async () => {
    const contents = (await render()) ?? '';
    expect(Object.keys(JSON.parse(contents) as object)[0]).toBe('//');
  });

  it('omits the marker when the manifest disables it', async () => {
    const contents =
      (await render((c) => ({
        ...c,
        manifest: { ...c.manifest, options: { ...c.manifest.options, marker: false } },
      }))) ?? '';
    expect(contents).not.toContain('generated by rulegate');
    expect(contents.startsWith('{\n  "mcpServers"')).toBe(true);
  });

  it('renders nothing when no server targets this tool', async () => {
    const artifacts = await (async () => {
      const ctx = await contextFor(`${FIXTURE}/input`, claudeCode);
      return claudeCode.write({ ...ctx, canonical: { ...ctx.canonical, mcpServers: [] } });
    })();
    expect(artifacts).toEqual([]);
  });

  it('renders one order whatever order the servers arrive in', async () => {
    // Deliberately NOT a test of `selectMcpServers`' sort: `stableJsonStringify` sorts every
    // key deeply, so an assertion on the id order here passes with that sort deleted —
    // verified by mutation. What this pins is the property that actually matters at this
    // level: the *bytes* do not depend on the order the servers were handed over, which is
    // what `state.json` hashes. The sort has its own guard in `core/test/mcp.test.ts`.
    const ctx = await contextFor(`${FIXTURE}/input`, claudeCode);
    const reversed: readonly McpServer[] = [...ctx.canonical.mcpServers].reverse();
    const rendered = async (servers: readonly McpServer[]) =>
      (
        await claudeCode.write({ ...ctx, canonical: { ...ctx.canonical, mcpServers: servers } })
      ).find((a) => a.path === MCP_FILE)?.contents;

    expect(await rendered(reversed)).toBe(await rendered(ctx.canonical.mcpServers));
  });

  it('still refuses to write over a canonical source', async () => {
    const contents = await render((c) => ({
      ...c,
      manifest: { ...c.manifest, canonicalSources: [MCP_FILE, CLAUDE_MD] },
    }));
    expect(contents).toBeUndefined();
  });
});
